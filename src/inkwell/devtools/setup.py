def build_status_table(profile: str | None = None) -> Table:
    """Build a rich table showing configuration status."""
    profile = profile or resolve_profile()
    env = read_env_local(profile)
    google = google_paths_for_profile(profile)
    google_creds, google_token = google.credentials, google.token

    title = f"Profile: [bold]{profile}[/]" if profile else "Default configuration"
    table = Table(title=title, show_header=False, box=None, padding=(0, 2))
    table.add_column("Status", width=3)
    table.add_column("Integration", min_width=30)
    table.add_column("Detail", style="dim")

    config_dir = env_value(env, PROVIDER_LOGIN.config_home_env)
    login_ok = bool(config_dir) and PROVIDER_LOGIN.logged_in(Path(config_dir))
    table.add_row(
        "[green]OK[/]" if login_ok else "[dim]--[/]",
        f"{RUNTIME.name} login",
        config_dir if login_ok else f"using default (shared with {RUNTIME.name})",
    )

    google_ok = google_token.exists()
    google_creds_ok = google_creds.exists()
    if google_ok:
        detail = "authorized"
    elif google_creds_ok:
        detail = "credentials present, not yet authorized"
    else:
        detail = "not configured"
    table.add_row(
        "[green]OK[/]" if google_ok else "[red]--[/]",
        "Google (Docs + Drive)",
        detail,
    )

    exa_ok = bool(env_value(env, "EXA_API_KEY"))
    table.add_row(
        "[green]OK[/]" if exa_ok else "[red]--[/]",
        "Exa",
        mask(env["EXA_API_KEY"]) if exa_ok else "not configured",
    )

    import asyncio

    from inkwell.agent.browser_auth import context_has_cookies

    has_browser = asyncio.run(context_has_cookies(profile))
    has_cookie = bool(env_value(env, "CLAUDE_COOKIE"))
    claude_ok = has_browser or has_cookie
    if has_browser:
        claude_detail = "browser session stored"
    elif has_cookie:
        claude_detail = f"cookie: {mask(env['CLAUDE_COOKIE'])}"
    else:
        claude_detail = "not configured"
    table.add_row(
        "[green]OK[/]" if claude_ok else "[dim]--[/]",
        "Claude.ai session",
        claude_detail,
    )

    fred_ok = bool(env_value(env, "FRED_API_KEY"))
    table.add_row(
        "[green]OK[/]" if fred_ok else "[dim]--[/]",
        "FRED",
        mask(env["FRED_API_KEY"]) if fred_ok else "not configured (optional)",
    )

    return table


@app.command("status")
def status() -> None:
    """Show current integration status."""
    console.print()
    console.print(build_status_table())
    console.print()


