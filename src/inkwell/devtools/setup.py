def read_env_file(path: Path) -> EnvVars:
    """Parse an env file into a dict. Returns empty dict if file missing.

    Through dotenv, which is the parser pydantic-settings itself reads these
    files with — so what the wizard reports as configured is what a run will
    actually load, quoting and continuations included.
    """
    if not path.exists():
        return {}
    return {key: value for key, value in dotenv_values(path).items() if value}


def env_value(env: EnvVars, key: str) -> str:
    """The value an env file carries for `key`, or empty where it carries none.

    An env file holds whatever keys someone put in it, so a miss is ordinary
    and every caller here treats absent and blank the same way.
    """
    return env[key] if key in env else ""


def overwrite_env_file(path: Path, values: EnvVars) -> None:
    """Write values as the entire env file, replacing whatever was there."""
    lines = ["# Auto-generated by lup-devtools setup", ""]
    for key, value in sorted(values.items()):
        if ";" in value:
            lines.append(f"{key}='{value}'")
        else:
            lines.append(f"{key}={value}")
    lines.append("")

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines))


def write_env_file(path: Path, values: EnvVars) -> None:
    """Write values to an env file, preserving existing entries."""
    existing = read_env_file(path)
    existing.update(values)
    overwrite_env_file(path, existing)


def read_env_local(profile: str | None = None) -> EnvVars:
    """Parse the active profile's env file into a dict."""
    return read_env_file(env_file_for_profile(profile or resolve_profile()))


def write_env_local(values: EnvVars, profile: str | None = None) -> None:
    """Write values to the active profile's env file."""
    write_env_file(
        env_file_for_profile(profile or resolve_profile()),
        values,
    )


def clear_env_local(keys: Iterable[str], profile: str | None = None) -> None:
    """Drop keys from the active profile's env file."""
    clear_env_file(env_file_for_profile(profile or resolve_profile()), keys)


# Env keys each integration owns, keyed by the stable id the dashboard sends.
# Resetting an integration drops exactly these; those that also own files clear
# them in reset_integration below.
RESETTABLE_ENV_KEYS: dict[str, tuple[str, ...]] = {
    "google": ("GOOGLE_CREDENTIALS_PATH", "GOOGLE_TOKEN_PATH"),
    "session": ("CLAUDE_COOKIE", "CLAUDE_ORG_UUID"),
    "author": ("INKWELL_AUTHOR_EMAIL",),
    "exa": ("EXA_API_KEY",),
    "fred": ("FRED_API_KEY",),
    "claude-login": (PROVIDER_LOGIN.config_home_env,),
}


def reset_integration(integration: str, profile: str | None = None) -> None:
    """Erase everything one integration configured for a profile.

    The inverse of authorizing it: drop the integration's env keys and delete any
    on-disk artifacts it owns — Google's OAuth client and token, the claude.ai
    durable browser session — so it reads "not configured" and can be redone from
    scratch, without deleting the whole profile. Raises ``KeyError`` for an
    unknown integration id.
    """
    clear_env_local(RESETTABLE_ENV_KEYS[integration], profile)
    match integration:
        case "google":
            paths = google_paths_for_profile(profile)
            paths.credentials.unlink(missing_ok=True)
            paths.token.unlink(missing_ok=True)
        case "session":
            from inkwell.agent.browser_auth import clear_context

            clear_context(profile)


def save_and_confirm(values: EnvVars) -> None:
    """Write values to the active env file and print confirmation."""
    if values:
        profile = resolve_profile()
        write_env_local(values, profile)
        target = env_file_for_profile(profile)
        console.print(f"[green]Saved to {target.relative_to(PROJECT_ROOT)}[/]")


def mask(value: str, show: int = 6) -> str:
    """Mask a secret string, showing only the first few characters."""
    if len(value) <= show:
        return value
    return value[:show] + "..." + "*" * min(8, len(value) - show)


class GraphicalSession(BaseSettings):
    """Whether the host advertises a display server a browser could open on."""

    model_config = SettingsConfigDict(extra="ignore")

    display: str = Field(default="", validation_alias="DISPLAY")
    wayland_display: str = Field(default="", validation_alias="WAYLAND_DISPLAY")


def has_graphical_display() -> bool:
    """Check whether a graphical browser is likely available."""
    session = GraphicalSession()
    if session.display or session.wayland_display:
        return True
    if shutil.which("open") and os.uname().sysname == "Darwin":
        return True
    return False


def open_browser(url: str) -> None:
    """Open a URL in the default browser, with fallback message.

    Skips webbrowser.open() when no graphical display is detected to
    avoid launching terminal browsers (elinks, lynx) that block the
    process.
    """
    console.print(f"  Opening [link={url}]{url}[/link]")
    if not has_graphical_display():
        console.print(f"  [dim]No graphical display — go to: {url}[/dim]")
        return
    try:
        webbrowser.open(url)
    except OSError:
        console.print(f"  [dim]Could not open browser. Go to: {url}[/dim]")


