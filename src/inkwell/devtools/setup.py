"""Interactive setup wizard for Inkwell integrations.

Walks through configuring Google (Docs + Drive), Exa, Claude cookie,
and FRED API key. Writes secrets to .env.local and handles the Google
OAuth browser flow.

Usage::

    $ uv run lup-devtools setup          # Full walkthrough
    $ uv run lup-devtools setup google   # Just Google OAuth
    $ uv run lup-devtools setup status   # Show what's configured
"""

from __future__ import annotations

import shutil
import webbrowser
from collections.abc import Callable
from pathlib import Path

import typer
from rich.console import Console
from rich.panel import Panel
from rich.table import Table

app = typer.Typer(
    help="Interactive setup wizard",
    pretty_exceptions_show_locals=False,
    invoke_without_command=True,
)

console = Console()

PROJECT_ROOT = Path(__file__).resolve().parents[3]
ENV_LOCAL = PROJECT_ROOT / ".env.local"
CREDENTIALS_DIR = PROJECT_ROOT / "credentials"
GOOGLE_CREDS_PATH = CREDENTIALS_DIR / "google.json"
GOOGLE_TOKEN_PATH = CREDENTIALS_DIR / "token.json"


# =====================================================================
# .env.local helpers
# =====================================================================


def read_env_local() -> dict[str, str]:
    """Parse .env.local into a dict. Returns empty dict if file missing."""
    if not ENV_LOCAL.exists():
        return {}
    values: dict[str, str] = {}
    for line in ENV_LOCAL.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if "=" not in line:
            continue
        key, _, value = line.partition("=")
        values[key.strip()] = value.strip()
    return values


def write_env_local(values: dict[str, str]) -> None:
    """Write values to .env.local, preserving existing entries."""
    existing = read_env_local()
    existing.update(values)

    lines = ["# Auto-generated by lup-devtools setup", ""]
    for key, value in sorted(existing.items()):
        lines.append(f"{key}={value}")
    lines.append("")

    ENV_LOCAL.write_text("\n".join(lines))


def save_and_confirm(values: dict[str, str]) -> None:
    """Write values to .env.local and print confirmation."""
    if values:
        write_env_local(values)
        console.print("[green]Saved to .env.local[/]")


def mask(value: str, show: int = 6) -> str:
    """Mask a secret string, showing only the first few characters."""
    if len(value) <= show:
        return value
    return value[:show] + "..." + "*" * min(8, len(value) - show)


def open_browser(url: str) -> None:
    """Open a URL in the default browser, with fallback message."""
    console.print(f"  Opening [link={url}]{url}[/link]")
    try:
        webbrowser.open(url)
    except OSError:
        console.print(f"  [dim]Could not open browser. Go to: {url}[/dim]")


# =====================================================================
# Status display
# =====================================================================


def build_status_table() -> Table:
    """Build a rich table showing configuration status."""
    env = read_env_local()

    table = Table(show_header=False, box=None, padding=(0, 2))
    table.add_column("Status", width=3)
    table.add_column("Integration", min_width=30)
    table.add_column("Detail", style="dim")

    google_ok = GOOGLE_TOKEN_PATH.exists()
    google_creds_ok = GOOGLE_CREDS_PATH.exists()
    if google_ok:
        detail = "authorized"
    elif google_creds_ok:
        detail = "credentials present, not yet authorized"
    else:
        detail = "not configured"
    table.add_row(
        "[green]OK[/]" if google_ok else "[red]--[/]",
        "Google (Docs + Drive)",
        detail,
    )

    exa_ok = bool(env.get("EXA_API_KEY"))
    table.add_row(
        "[green]OK[/]" if exa_ok else "[red]--[/]",
        "Exa",
        mask(env["EXA_API_KEY"]) if exa_ok else "not configured",
    )

    claude_ok = bool(env.get("CLAUDE_COOKIE"))
    table.add_row(
        "[green]OK[/]" if claude_ok else "[dim]--[/]",
        "Claude cookie",
        mask(env["CLAUDE_COOKIE"]) if claude_ok else "not configured (optional)",
    )

    fred_ok = bool(env.get("FRED_API_KEY"))
    table.add_row(
        "[green]OK[/]" if fred_ok else "[dim]--[/]",
        "FRED",
        mask(env["FRED_API_KEY"]) if fred_ok else "not configured (optional)",
    )

    return table


@app.command("status")
def status() -> None:
    """Show current integration status."""
    console.print()
    console.print(build_status_table())
    console.print()


