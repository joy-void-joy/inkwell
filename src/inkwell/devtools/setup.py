def setup_claude() -> EnvVars:
    """Walk through Claude.ai session setup via managed browser. Returns env vars to set."""
    import asyncio

    from inkwell.agent.browser_auth import context_has_cookies, login_interactive

    profile = resolve_profile()

    console.print()
    console.rule("[bold]Claude.ai session[/]")
    console.print()

    if asyncio.run(context_has_cookies(profile)):
        console.print("[green]Browser session already stored.[/]")
        if not typer.confirm("Re-login?", default=False):
            return {}

    console.print(
        "  Used to extract conversations from Claude share links.\n"
        "  A dedicated browser window will open — log in to claude.ai.\n"
        "  [dim]This session is stored separately from your main browser,[/]\n"
        "  [dim]so logging out of Chrome won't affect extraction.[/]\n"
    )

    if not has_graphical_display():
        cmd = "inkwell setup claude"
        if profile:
            cmd += f" --profile {profile}"
        console.print(
            "  [yellow]No graphical display detected.[/]\n"
            "  Run this in your terminal to log in with a browser:\n"
            f"\n"
            f"    [bold]! {cmd}[/]\n"
            f"\n"
            "  Or paste a cookie manually:\n"
        )
        cookie = typer.prompt(
            "CLAUDE_COOKIE (or press Enter to skip)",
            default="",
            show_default=False,
        ).strip()
        if cookie:
            return {"CLAUDE_COOKIE": cookie}
        return {}

    if not typer.confirm("Open browser to log in?", default=True):
        return {}

    logged_in = asyncio.run(login_interactive(profile))
    if logged_in:
        console.print("[green]Login successful — session saved.[/]")
    else:
        console.print("[yellow]Login may not have completed.[/]")
        console.print("  Retry with: [bold]uv run lup-devtools setup claude[/]")

    return {}


