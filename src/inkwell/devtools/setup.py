def place_google_credentials(target_dir: Path, target_path: Path) -> None:
    """Prompt user for credentials JSON path and copy to target."""
    source = typer.prompt(
        "Path to downloaded credentials JSON",
    ).strip()
    source_path = Path(source).expanduser().resolve()

    if not source_path.exists():
        console.print(f"[red]File not found:[/] {source_path}")
        raise typer.Abort()

    target_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source_path, target_path)
    console.print(f"  Copied to [bold]{target_path}[/]")


def setup_google() -> EnvVars:
    """Walk through Google OAuth setup step by step. Returns env vars to set."""
    profile = resolve_profile()
    google = google_paths_for_profile(profile)
    creds_path, token_path = google.credentials, google.token

    console.print()
    console.rule("[bold]Google (Docs + Drive)[/]")
    console.print()

    if token_path.exists():
        console.print("[green]Already authorized.[/]")
        if not typer.confirm("Re-authorize?", default=False):
            return {
                "GOOGLE_CREDENTIALS_PATH": str(creds_path),
                "GOOGLE_TOKEN_PATH": str(token_path),
            }

    if not creds_path.exists():
        console.print("  [bold]Step 1:[/] Create a Google Cloud project\n")
        open_browser("https://console.cloud.google.com/projectcreate")
        typer.prompt(
            "  Press Enter when your project is created", default="", show_default=False
        )

        console.print("\n  [bold]Step 2:[/] Enable Google Docs API")
        open_browser(
            "https://console.cloud.google.com/apis/library/docs.googleapis.com"
        )
        typer.prompt("  Press Enter after enabling", default="", show_default=False)

        console.print("\n  [bold]Step 3:[/] Enable Google Drive API")
        open_browser(
            "https://console.cloud.google.com/apis/library/drive.googleapis.com"
        )
        typer.prompt("  Press Enter after enabling", default="", show_default=False)

        console.print(
            "\n  [bold]Step 4a:[/] Configure OAuth consent screen\n"
            "  [dim]Select External > Create, fill in app name + your email, skip scopes.[/]"
        )
        open_browser("https://console.cloud.google.com/apis/credentials/consent")
        typer.prompt(
            "  Press Enter when consent screen is created",
            default="",
            show_default=False,
        )

        console.print(
            "\n  [bold]Step 4b:[/] Add a test user\n"
            "  [bold yellow]Important:[/] Click [bold]+ Add users[/] and enter the Google email\n"
            "  you'll authorize with. This can be a different account than the\n"
            "  project owner — add whichever email you'll sign in with next.\n"
            "  Without this, the OAuth flow will fail with [dim]Error 403: access_denied[/]."
        )
        open_browser("https://console.cloud.google.com/auth/audience")
        typer.prompt(
            "  Press Enter when the email is added as a test user",
            default="",
            show_default=False,
        )

        console.print(
            "\n  [bold]Step 5:[/] Create OAuth client ID\n"
            '  [dim]Click "Create Credentials" > OAuth client ID > Desktop app > Create\n'
            "  Then download the JSON file[/]"
        )
        open_browser("https://console.cloud.google.com/apis/credentials")
        console.print()
        place_google_credentials(creds_path.parent, creds_path)
    else:
        console.print(f"  Using existing credentials at [bold]{creds_path}[/]")
        console.print(
            '\n  [bold yellow]Note:[/] If you see [dim]"app not verified"[/] or [dim]"access denied"[/],\n'
            "  make sure the account you're signing in with is listed as a test user\n"
            "  on the project (this can differ from the project owner):\n"
            "  https://console.cloud.google.com/auth/audience\n"
        )

    console.print(
        "  [bold]Authorizing...[/] Grant access to Google Docs and Drive in the browser."
    )
    console.print()

    try:
        from inkwell.agent.google_auth import run_oauth_flow

        run_oauth_flow(str(creds_path), str(token_path))
        console.print(f"[green]Google authorized![/] Token saved to {token_path}")
    except FileNotFoundError as e:
        console.print(f"[red]Error:[/] {e}")
        return {}
    except AccessDeniedError:
        print_test_user_guidance()
        return {}
    except RuntimeError as e:
        error_msg = str(e).lower()
        if "access_denied" in error_msg or "verification" in error_msg:
            print_test_user_guidance()
        else:
            console.print(f"[red]OAuth flow failed:[/] {e}")
            console.print("Retry with: [bold]uv run lup-devtools setup google[/]")
        return {}

    return {
        "GOOGLE_CREDENTIALS_PATH": str(creds_path),
        "GOOGLE_TOKEN_PATH": str(token_path),
    }


