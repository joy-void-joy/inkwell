def setup_exa() -> dict[str, str]:
    """Walk through Exa configuration. Returns env vars to set."""
    console.print()
    console.rule("[bold]Exa[/]")
    console.print()

    env = read_env_local()

    if env.get("EXA_API_KEY"):
        console.print("[green]Already configured.[/]")
        if not typer.confirm("Reconfigure?", default=False):
            return {}

    console.print("  AI-powered web search for research.\n")
    open_browser("https://dashboard.exa.ai/api-keys")
    console.print()

    key = typer.prompt(
        "EXA_API_KEY",
        default=env.get("EXA_API_KEY", ""),
        show_default=False,
    ).strip()

    if key:
        return {"EXA_API_KEY": key}
    return {}


