def setup_claude_login() -> EnvVars:
    """Set up a separate Claude login for the writing agent."""
    import sh

    profile = resolve_profile()
    config_dir = claude_config_dir_for_profile(profile)

    console.print()
    console.rule("[bold]Claude login[/]")
    console.print()

    env = read_env_local(profile)
    existing_dir = env_value(env, PROVIDER_LOGIN.config_home_env)

    if existing_dir and Path(existing_dir).exists():
        if PROVIDER_LOGIN.logged_in(Path(existing_dir)):
            console.print(
                f"[green]Already configured.[/] Using [bold]{existing_dir}[/]"
            )
            if not typer.confirm("Re-login?", default=False):
                return {}

    console.print(
        "  Inkwell's writing agent uses Claude Code under the hood.\n"
        "  By default it shares your current Claude Code login.\n"
        "\n"
        "  You can log in with a separate account so the agent's\n"
        "  usage is billed separately from your dev session.\n"
    )

    if not typer.confirm("Set up a separate login?", default=bool(existing_dir)):
        return {}

    config_dir.mkdir(parents=True, exist_ok=True)

    console.print(
        f"\n  Logging in with config dir: [bold]{config_dir}[/]\n"
        "  A browser window will open — sign in with the account\n"
        "  you want the writing agent to use.\n"
    )

    login_env = {
        **os.environ,  # lup: ignore[os-environ] — exact child-process inheritance
        **PROVIDER_LOGIN.environment(config_dir),
    }
    claude = sh.Command("claude")
    try:
        claude("/login", _env=login_env, _fg=True)
    except sh.ErrorReturnCode:
        console.print(
            "[red]Login failed.[/] Retry with: [bold]uv run lup-devtools setup claude-login[/]"
        )
        return {}

    console.print("[green]Logged in![/]")
    return PROVIDER_LOGIN.environment(config_dir)


